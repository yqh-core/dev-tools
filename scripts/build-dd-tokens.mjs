/**
 * B3 · 把 dd-tokens.css 编译成 JS 令牌模块。
 *
 * 为什么需要这一步（实测结论，不是推测）：
 *   Naive UI 会对 primaryColor 等值做颜色运算（seemly/rgba）。
 *   直接写 'var(--dd-primary)' 会抛 `[seemly/rgba]: Invalid color value var(--dd-primary)`，
 *   暗色下整页不渲染 —— 而它是 console.error 不是 throw，很容易被漏掉。
 *   所以 Naive 侧必须拿到**真实色值字符串**。
 *
 * 但「真实色值」不等于要把十六进制再抄一份（抄一份就是第二个事实来源，必然漂移）。
 * 所以在**构建期**从唯一的 CSS 文件读出来生成 TS 模块：
 *   public/css/dd-tokens.css  ──(本脚本)──▶  src/generated/dd-tokens.ts
 * 改色只需要改 dd-tokens.css（它由 _ops/sync-design-tokens.mjs 分发到 6 个站）。
 *
 * 用法：
 *   node scripts/build-dd-tokens.mjs           # 生成
 *   node scripts/build-dd-tokens.mjs --check   # 只校验磁盘文件与 CSS 是否一致（不一致 exit 1）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSS_SRC = path.join(ROOT, 'public/css/dd-tokens.css');
const OUT = path.join(ROOT, 'src/generated/dd-tokens.ts');

if (!fs.existsSync(CSS_SRC)) {
  console.error(`[dd-tokens] 找不到 ${CSS_SRC} —— 令牌源缺失，拒绝生成（否则会静默产出空令牌）`);
  process.exit(2);
}

const css = fs.readFileSync(CSS_SRC, 'utf8');

/** 取出指定选择器块里的 `--dd-x: value;` 声明 */
function extractBlock(selectorRe) {
  const m = selectorRe.exec(css);
  if (!m) return null;
  // 从匹配处找到配对的 { }
  const start = css.indexOf('{', m.index);
  if (start < 0) return null;
  let depth = 0;
  let end = -1;
  for (let i = start; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}') { depth--; if (depth === 0) { end = i; break; } }
  }
  if (end < 0) return null;
  return css.slice(start + 1, end);
}

function parseVars(block) {
  if (!block) return {};
  const out = {};
  const re = /--dd-([a-z0-9-]+)\s*:\s*([^;]+);/g;
  let m;
  while ((m = re.exec(block))) {
    const key = m[1].replace(/-/g, '_');
    out[key] = m[2].trim().replace(/\s+/g, ' ');
  }
  return out;
}

const light = parseVars(extractBlock(/:root\s*\{/));
const darkBlock = parseVars(extractBlock(/html\[data-theme="dark"\]\s*,\s*html\.dark\s*\{/));

// CSS 里暗色块只覆盖部分变量，其余从 :root 继承。
// JS 侧必须做同样的合并，否则 ddTokens.dark.radius 会是 undefined —— 那是个「看着有、实际没有」的坑。
const dark = { ...light, ...darkBlock };

// 负样本自证：解析结果不能是空的，否则「生成成功」是假的
if (Object.keys(light).length < 10) {
  console.error(`[dd-tokens] :root 只解析出 ${Object.keys(light).length} 个变量 —— 解析器或源文件有问题，拒绝覆盖产物`);
  process.exit(2);
}
if (Object.keys(dark).length < 10) {
  console.error(`[dd-tokens] 暗色块只解析出 ${Object.keys(dark).length} 个变量 —— 拒绝覆盖产物`);
  process.exit(2);
}
const inherited = Object.keys(light).filter(k => !(k in darkBlock));
if (inherited.length > 0) {
  console.log(`[dd-tokens] 暗色继承 :root 的 ${inherited.length} 项：${inherited.join(', ')}`);
}

const fmt = (o) => Object.entries(o).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`).join('\n');

const content = `/* AUTO-GENERATED by scripts/build-dd-tokens.mjs —— 请勿手改。
 * 源：public/css/dd-tokens.css（由 _ops/sync-design-tokens.mjs 分发）
 * 改色请改 dd-tokens.css，然后 npm run build（构建会自动重新生成）。
 */
export const ddTokens = {
  light: {
${fmt(light)}
  },
  dark: {
${fmt(dark)}
  },
} as const;

export type DdTheme = keyof typeof ddTokens;
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== content) {
    console.error('[dd-tokens] --check 失败：src/generated/dd-tokens.ts 与 dd-tokens.css 不一致');
    process.exit(1);
  }
  console.log(`[dd-tokens] --check 通过：light ${Object.keys(light).length} 项 / dark ${Object.keys(dark).length} 项，与 CSS 一致`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, content);
console.log(`[dd-tokens] 已生成 ${path.relative(ROOT, OUT)}：light ${Object.keys(light).length} 项 / dark ${Object.keys(dark).length} 项`);
