// ─────────────────────────────────────────────────────────────────────────────
// 干跑实现：对每个目标做「定位 → 计数校验 → 生成预览后内容」，不写盘。
// ─────────────────────────────────────────────────────────────────────────────

const results = [];
let failed = false;

/**
 * 本仓库工作区的 .mjs/.ts/.yml 实测是 CRLF 行尾（git 里归一成 LF，所以 git status 干净）。
 * 匹配一律在归一化后的文本上做；写回时按**原文件的行尾风格**还原，
 * 否则 `--apply` 那天会产生「整文件行尾翻转」的巨型 diff，把真正的删除行埋掉。
 */
function load(p) {
  const raw = fs.readFileSync(path.join(ROOT, p), 'utf8');
  return { raw, eol: raw.includes('\r\n') ? '\r\n' : '\n', text: raw.replaceAll('\r\n', '\n') };
}

function countMatches(lines, anchor) {
  if (anchor instanceof RegExp) {
    return lines.map((l, i) => (anchor.test(l) ? i : -1)).filter((i) => i >= 0);
  }
  return lines.map((l, i) => (l.includes(anchor) ? i : -1)).filter((i) => i >= 0);
}

function applyCut(text, target) {
  const lines = text.split('\n');
  if (target.op === 'cutLine') {
    const hits = countMatches(lines, target.anchor);
    if (hits.length !== target.expect) {
      throw new Error(`锚命中 ${hits.length} 次，期望 ${target.expect} 次${hits.length ? `（行 ${hits.map(h => h + 1).join(',')}）` : ''}`);
    }
    const drop = new Set(hits);
    return { next: lines.filter((_, i) => !drop.has(i)).join('\n'), removed: hits.map(h => lines[h]) };
  }
  if (target.op === 'cutBlock') {
    const starts = countMatches(lines, target.startAnchor);
    if (starts.length !== 1) throw new Error(`起点锚命中 ${starts.length} 次，期望 1 次`);
    let start = starts[0] - (target.leadFromStart ?? 0);
    if (start < 0) throw new Error('leadFromStart 越界');
    let end = -1;
    if (target.balance) {
      // TS 对象条目：从起点行开始按花括号配平找闭合行。
      // ⚠ 这里有两层历史踩坑：① 拿「锚文本最后一次出现」当块尾 ——
      //    `  },` 这种锚在文件里出现几十次，直接命中最远的一次，一刀删掉 320 行；
      //    ② 改成「起点后第一个 } 收尾」—— faqs 数组里每行都以 `},` 结尾，会在块内部提前收口。
      //    两条都错，所以按深度计数：统计 `{`/`}` 净增减，深度回到 0 的那行才是本条目的收尾。
      let depth = 0;
      for (let i = start; i < lines.length; i += 1) {
        for (const ch of lines[i]) {
          if (ch === '{') depth += 1;
          else if (ch === '}') depth -= 1;
        }
        if (depth === 0 && i > start) { end = i; break; }
        if (depth < 0) throw new Error('花括号配平失败（起点前已有不闭合的 {）');
      }
      if (end < 0) throw new Error('找不到花括号闭合行');
    } else {
      // yml / 冒烟用例这类短块：起点之后**第一个**匹配终点锚的行即块尾。
      // 注意是「第一个」而不是「最后一个」—— 最后一个会把整文件吞掉。
      const ends = countMatches(lines.slice(start), target.endAnchor).map((i) => i + start);
      if (ends.length < 1) throw new Error('起点之后找不到终点锚');
      end = ends[0];
    }
    // 顺带吃掉块后紧跟的空行，防止留下连续两个空行破坏 prettier 规则
    let tail = end + 1;
    if (lines[tail] === '') tail += 1;
    const removed = lines.slice(start, tail);
    if (target.maxLines && removed.length > target.maxLines) {
      throw new Error(`块尺寸 ${removed.length} 行 > 上限 ${target.maxLines} 行 —— 判据本身失效，宁可红也不误删`);
    }
    return {
      next: [...lines.slice(0, start), ...lines.slice(tail)].join('\n'),
      removed,
    };
  }
  throw new Error(`未知算子 ${target.op}`);
}

const cache = new Map(); // path -> { eol, text, dirty }

for (const t of TARGETS) {
  const entry = { id: t.id, op: t.op, path: t.path, note: t.note };
  try {
    if (t.op === 'removeDir') {
      const abs = path.join(ROOT, t.path);
      if (!fs.existsSync(abs)) throw new Error('目录不存在');
      const found = fs.readdirSync(abs).sort();
      const missing = t.expectFiles.filter((f) => !found.includes(f));
      if (missing.length) throw new Error(`目录内缺少预期文件：${missing.join(', ')}`);
      entry.status = 'ok';
      entry.detail = `整目录删除：${t.path}/（${found.join(', ')}）`;
      entry.affectedLines = found.reduce((n, f) => n + r(path.join(t.path, f)).split('\n').length, 0);
    } else {
      if (!cache.has(t.path)) {
        const f = load(t.path);
        cache.set(t.path, { eol: f.eol, text: f.text, dirty: false });
      }
      const cur = cache.get(t.path);
      const { next, removed } = applyCut(cur.text, t);
      entry.status = 'ok';
      entry.affectedLines = removed.length;
      entry.lineEnding = cur.eol === '\r\n' ? 'CRLF' : 'LF';
      entry.removedPreview = removed.map((l) => l.trim().slice(0, 120));
      cur.text = next;
      cur.dirty = true;
      if (PREVIEW) {
        console.log(`\n──── ${t.id} (${t.path}) 将删除的行 ────`);
        console.log(removed.map((l) => `- ${l}`).join('\n'));
      }
    }
  } catch (e) {
    entry.status = 'FAIL';
    entry.error = String(e.message || e);
    failed = true;
  }
  results.push(entry);
}

if (APPLY) {
  for (const [p, cur] of cache) {
    if (cur.dirty) fs.writeFileSync(path.join(ROOT, p), cur.text.replaceAll('\n', cur.eol), 'utf8');
  }
  // removeDir 走 git rm，保留可回滚性（不用 fs 级永久删除）
  for (const t of TARGETS) {
    if (t.op === 'removeDir') execSync(`git rm -r -- "${t.path}"`, { cwd: ROOT, stdio: 'inherit' });
  }
}

// 全仓兜底扫描：除白名单外，任何残留引用都是「清单没钉住的第 N 处」→ 直接判 FAIL。
// 这正是本工具存在的意义：把「我以为删干净了」变成机器判据。
// ⚠ 必须带 --untracked：删除当天新建的文件（如 _redirects 草稿、迁移脚本）不在索引里，
//   纯 git grep 看不见它们 —— 实测注入一个未跟踪 canary 文件，兜底扫描照样报 0 残留（假绿）。
const WHITESPAN = new Set([
  'scripts/email-normalizer-teardown.mjs',
  'scripts/email-normalizer-teardown.manifest.json',
  'components.d.ts', // unplugin-vue-components 构建期生成，见 AUTOGENERATED
  'pnpm-lock.yaml', // 锁文件由维护窗口单独处置，见 npm-dep 条 note
]);
const residual = [];
// 排除语法用 git 的 pathspec magic（`:(exclude)…`），不是 shell 的 `:!…`（那是 zsh 的）
const grep = execSync('git grep --untracked -l email-normalizer -- ":(exclude)dist"', { cwd: ROOT, encoding: 'utf8' });
for (const f of grep.split('\n').map((s) => s.trim()).filter(Boolean)) {
  if (WHITESPAN.has(f)) continue;
  if (!TARGETS.some((t) => t.path === f || f.startsWith(t.path + '/'))) residual.push(f);
}

const manifest = {
  generatedAt: new Date().toISOString(),
  mode: APPLY ? 'APPLY' : 'DRY-RUN',
  baselineHead: execSync('git rev-parse HEAD', { cwd: ROOT, encoding: 'utf8' }).trim(),
  branch: execSync('git symbolic-ref --short HEAD', { cwd: ROOT, encoding: 'utf8' }).trim(),
  removalTargets: results,
  autogeneratedNotTouched: AUTOGENERATED,
  routingTodos: ROUTING_TODO,
  residualFilesOutsideChecklist: residual,
  verdict: failed ? 'CHECKLIST-BROKEN' : residual.length ? 'RESIDUAL-REFS' : 'TEARDOWN-PATH-PROVEN',
};

fs.writeFileSync(OUT, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

for (const e of results) {
  console.log(`[${e.status}] ${e.id.padEnd(18)} ${e.path}${e.error ? ' — ' + e.error : ''}`);
}
console.log(`\n清单外残留引用：${residual.length ? residual.join(', ') : '0 处'}`);
console.log(`manifest → ${rel(OUT)}`);
console.log(`VERDICT: ${manifest.verdict}${APPLY ? '（已落盘！）' : '（未落盘，工作区零改动）'}`);
process.exit(failed || residual.length ? 1 : 0);
