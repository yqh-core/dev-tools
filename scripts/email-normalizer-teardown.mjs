/**
 * email-normalizer-teardown.mjs —— /email-normalizer 下线前的「可回滚拆除准备」
 * ----------------------------------------------------------------------------
 * 背景（好点子台账 B 区）：该页与 /pdf-signature-checker 同为删除候选，
 * 台账记录的拆除面是「各 7 处」。本脚本把拆除面逐条钉死成机器判据：
 * 每一条 = 一个可定位的锚点 + 期望命中数，任何一条找不到 / 多找都判 FAIL，
 * 这样「真正执行删除那天」不会出现「以为删干净了、其实漏了 guides」的情况。
 *
 * ⚠ 今晚只跑 dry-run（默认行为）：不写回任何文件、不删任何文件。
 *   --preview 会把「删完之后的文件内容」打到 stdout 供人复核；
 *   --apply 才会落盘 —— 留给正式的删除窗口，且必须先建回滚分支。
 *
 * 用法：
 *   node scripts/email-normalizer-teardown.mjs            # 盘点 + 自检 + 写 manifest
 *   node scripts/email-normalizer-teardown.mjs --preview  # 额外打印每个文件删除后的样子
 *   node scripts/email-normalizer-teardown.mjs --apply    # 真正落盘（今晚不使用）
 *
 * 回滚方式（因为不动 git，回滚 = 恢复工作区）：
 *   git status --porcelain            # 应只含本工具清单内路径
 *   git checkout -- <清单内文件>      # 或整分支 git reset --hard <baseline>
 */
